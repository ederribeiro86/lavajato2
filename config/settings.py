BASE_DIR = Path(__file__).resolve().parent.parent


def get_boolean_env(name, default):
    value = env_config(name, default=str(default))
    if isinstance(value, bool):
        return value

    normalized = str(value).strip().lower()
    if normalized in {'1', 'true', 'yes', 'on'}:
        return True
    if normalized in {'0', 'false', 'no', 'off'}:
        return False
    raise ImproperlyConfigured(f'{name} deve ser um valor booleano.')


def get_database_config():
    db_name = env_config('DB_NAME')

    if not db_name:
        return {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }

    db_user = env_config('DB_USER')
    db_password = env_config('DB_PASSWORD')

    if not all((db_user, db_password)):
        raise ImproperlyConfigured(
            'Defina DB_USER e DB_PASSWORD no arquivo .env para usar PostgreSQL.'
        )

    return {
        'ENGINE': 'django.db.backends.postgresql',
        'NAME': db_name,
        'USER': db_user,
        'PASSWORD': db_password,
        'HOST': env_config('DB_HOST', default='localhost'),
        'PORT': env_config('DB_PORT', default='5432'),
    }


